"""Normalised event contract published to Fabric Eventstream.

One envelope for every source and entity type, so a single Eventstream →
Eventhouse table can land everything and KQL update policies fan it out.
See docs/data-contracts.md for the field-by-field contract.
"""

from __future__ import annotations

import hashlib
import json
import uuid
from datetime import UTC, datetime
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_serializer, field_validator

SCHEMA_VERSION = "1.0"

# Namespace for deterministic UUIDv5 event ids.
_EVENT_NS = uuid.UUID("6f1f3c3e-5d0e-4c55-9a0e-2f7f6b2f9a11")


class Source(StrEnum):
    OHGO = "ohgo"
    NWS = "nws"
    MVOI = "mvoi"  # events generated by this platform (risk, alerts, heartbeats)


class EntityType(StrEnum):
    INCIDENT = "incident"
    CONSTRUCTION = "construction"
    DANGEROUS_SLOWDOWN = "dangerous_slowdown"
    TRAVEL_DELAY = "travel_delay"
    WEATHER_ALERT = "weather_alert"
    FACILITY_RISK = "facility_risk"
    OPERATIONAL_ALERT = "operational_alert"
    INGESTION_HEARTBEAT = "ingestion_heartbeat"


TRANSPORT_TYPES = {
    EntityType.INCIDENT,
    EntityType.CONSTRUCTION,
    EntityType.DANGEROUS_SLOWDOWN,
    EntityType.TRAVEL_DELAY,
}


class ChangeType(StrEnum):
    CREATED = "created"      # first observation of an entity
    UPDATED = "updated"      # material content changed
    RESOLVED = "resolved"    # absent long enough per lifecycle policy, or expired
    REOPENED = "reopened"    # reappeared after being resolved
    SNAPSHOT = "snapshot"    # state-carrying events (risk, heartbeat)


class Severity(StrEnum):
    MINOR = "minor"
    MODERATE = "moderate"
    MAJOR = "major"
    CRITICAL = "critical"

    @property
    def rank(self) -> int:
        return _SEVERITY_RANK[self]


_SEVERITY_RANK = {Severity.MINOR: 1, Severity.MODERATE: 2, Severity.MAJOR: 3, Severity.CRITICAL: 4}


class RunMode(StrEnum):
    LIVE = "live"
    REPLAY = "replay"


def utcnow() -> datetime:
    return datetime.now(UTC)


def ensure_utc(value: datetime | None) -> datetime | None:
    if value is None:
        return None
    if value.tzinfo is None:
        # Sources documented as UTC but serialised without offset.
        return value.replace(tzinfo=UTC)
    return value.astimezone(UTC)


def stable_hash(payload: Any) -> str:
    """Order-independent SHA-256 of a JSON-serialisable payload."""
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":"), default=str)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


class NormalizedEvent(BaseModel):
    """Canonical event. Field names are the Eventhouse / Lakehouse column names."""

    model_config = ConfigDict(use_enum_values=True)

    schema_version: str = SCHEMA_VERSION
    event_id: str = ""  # deterministic; filled by `finalize()`
    entity_key: str     # "<source>:<entity_type>:<source_id>"
    source: Source
    entity_type: EntityType
    source_id: str
    change_type: ChangeType
    environment: str = "dev"
    run_mode: RunMode = RunMode.LIVE
    replay_session_id: str | None = None

    # Timing (all UTC)
    observed_at: datetime                   # when the poll that saw this ran
    source_updated_at: datetime | None = None
    first_seen_at: datetime | None = None
    last_seen_at: datetime | None = None
    start_time: datetime | None = None      # construction start / NWS onset
    end_time: datetime | None = None        # construction end / NWS expires
    ingested_at: datetime | None = None     # set by the publisher

    # Location
    latitude: float | None = None
    longitude: float | None = None
    geometry_geojson: str | None = None     # polygon / line as GeoJSON text
    route_name: str | None = None
    corridor_id: str | None = None
    direction: str | None = None
    location: str | None = None

    # Classification
    category: str | None = None
    status: str | None = None
    severity: Severity | None = None
    severity_rank: int | None = None
    is_road_closure: bool = False
    title: str | None = None
    description: str | None = None

    # Type-specific attributes and the lossless source record
    attributes: dict[str, Any] = Field(default_factory=dict)
    content_hash: str = ""
    raw: dict[str, Any] | None = None

    @field_validator("observed_at", "source_updated_at", "first_seen_at", "last_seen_at",
                     "start_time", "end_time", "ingested_at")
    @classmethod
    def _utc(cls, v: datetime | None) -> datetime | None:
        return ensure_utc(v)

    @field_validator("latitude")
    @classmethod
    def _lat(cls, v: float | None) -> float | None:
        if v is not None and not -90 <= v <= 90:
            raise ValueError(f"latitude out of range: {v}")
        return v

    @field_validator("longitude")
    @classmethod
    def _lon(cls, v: float | None) -> float | None:
        if v is not None and not -180 <= v <= 180:
            raise ValueError(f"longitude out of range: {v}")
        return v

    @field_serializer("observed_at", "source_updated_at", "first_seen_at", "last_seen_at",
                      "start_time", "end_time", "ingested_at")
    def _iso(self, v: datetime | None) -> str | None:
        return v.isoformat().replace("+00:00", "Z") if v else None

    def finalize(self) -> NormalizedEvent:
        """Fill severity_rank, content_hash and the deterministic event_id."""
        if self.severity is not None:
            self.severity_rank = Severity(self.severity).rank
        if not self.content_hash:
            self.content_hash = content_hash_of(self)
        # Same entity + change + content + run => same id. Publishing twice is
        # therefore detectable downstream (Eventhouse dedups on event_id).
        self.event_id = str(
            uuid.uuid5(
                _EVENT_NS,
                "|".join([self.entity_key, str(self.change_type), self.content_hash,
                          str(self.run_mode), self.replay_session_id or "",
                          # Snapshot events repeat with identical content by design.
                          self._iso(self.observed_at) if self.change_type == ChangeType.SNAPSHOT
                          else ""]),
            )
        )
        return self

    def to_wire(self) -> dict[str, Any]:
        return self.model_dump(mode="json")


# Fields that describe the event's *content*. Changes to anything else (poll
# time, links, etc.) are not "updates".
_CONTENT_FIELDS = (
    "latitude", "longitude", "geometry_geojson", "route_name", "direction", "location",
    "category", "status", "severity", "is_road_closure", "title", "description",
    "start_time", "end_time", "attributes",
)


def content_hash_of(event: NormalizedEvent) -> str:
    data = event.model_dump(mode="json", include=set(_CONTENT_FIELDS))
    # Round coordinates: sensor-derived points jitter in the 6th decimal.
    for key in ("latitude", "longitude"):
        if data.get(key) is not None:
            data[key] = round(data[key], 5)
    # Volatile sensor readings change every poll; only material bands count.
    data["attributes"] = {k: v for k, v in (data.get("attributes") or {}).items()
                          if not k.startswith("live_")}
    return stable_hash(data)


def make_entity_key(source: Source | str, entity_type: EntityType | str, source_id: str) -> str:
    return f"{Source(source).value}:{EntityType(entity_type).value}:{source_id}"


def deterministic_source_id(*parts: Any) -> str:
    """Identity for records whose source id is missing or unreliable."""
    return "h-" + stable_hash([str(p) for p in parts])[:24]
